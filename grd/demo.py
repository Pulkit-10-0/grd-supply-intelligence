"""Assam scenario generator. Every operating observation is synthetic, not GRD data."""

from datetime import date, timedelta
import hashlib
import math
import json

import numpy as np
from sqlalchemy import insert, select

from . import domain as d
from .models import Batch, Dataset, Demand, Job, Location, Organisation, Product, Route, User
from .security import passwords


def seed_demo(s, email, password, as_of=date(2026, 11, 1), seed=42):
    if s.scalar(select(User).where(User.email == email.lower())):
        raise ValueError("Demo user already exists; seed is non-destructive")
    org = Organisation(name="Assam demonstration network", mode="synthetic", scenario_on=as_of)
    s.add(org)
    s.flush()
    user = User(
        org_id=org.id,
        email=email.lower(),
        password_hash=passwords.hash(password),
        role="admin",
        location_ids=[],
    )
    s.add(user)
    s.flush()
    prefix = org.id[:8]
    locations = []
    for label, kind, district, lat, lon in [
        ("Guwahati central demo warehouse", "warehouse", "Kamrup Metropolitan", 26.145, 91.736),
        ("Guwahati demo distributor", "distributor", "Kamrup Metropolitan", 26.155, 91.745),
        ("Dibrugarh demo distributor", "distributor", "Dibrugarh", 27.4728, 94.912),
        ("Silchar demo distributor", "distributor", "Cachar", 24.833, 92.779),
        ("Jorhat demo distributor", "distributor", "Jorhat", 26.7509, 94.2037),
    ]:
        obj = Location(
            id=prefix + "-L" + str(len(locations)),
            org_id=org.id,
            name=label,
            kind=kind,
            district=district,
            latitude=lat,
            longitude=lon,
            coordinate_source="Approximate town centre; fictional operating site",
        )
        locations.append(obj)
        s.add(obj)
    products = []
    for name, unit, pack in [
        ("Paracetamol 500 mg demo presentation", "tablet", 10),
        ("Cetirizine 10 mg demo presentation", "tablet", 10),
        ("ORS demo presentation", "sachet", 1),
        ("Slow-moving demo product A", "unit", 1),
        ("Restricted-transfer demo product B", "unit", 1),
    ]:
        obj = Product(
            id=prefix + "-P" + str(len(products)),
            org_id=org.id,
            name=name,
            base_unit=unit,
            pack_size=pack,
            unit_cost_paise=100 * (len(products) + 1),
            transfer_allowed=len(products) != 4,
            provenance={
                "evidence_type": "synthetic",
                "note": "Illustrative product presentation, not GRD SKU or clinical substitution mapping",
            },
        )
        products.append(obj)
        s.add(obj)
    s.flush()
    for a in locations:
        for b in locations:
            if a.id == b.id or b.kind == "warehouse":
                continue
            lead = 1 if a.district == b.district else 4
            s.add(
                Route(
                    org_id=org.id,
                    origin_id=a.id,
                    destination_id=b.id,
                    lead_days=lead,
                    lead_days_upper=lead + 2,
                    min_shelf_days=7 if a == locations[1] else 30,
                    safety_days=2,
                    min_order=1,
                    cost_paise=5000,
                    permitted=not (a == locations[2] and b == locations[3]),
                    policy_source="Demo assumptions; requires GRD approval before pilot",
                )
            )
    manifest = {
        "name": "Assam synthetic operating scenario v1",
        "evidence_type": "synthetic",
        "geography": "Assam fictional network",
        "source_url": "generated by grd.demo",
        "licence": "Project-generated scenario; no real company or patient observations",
        "units": "product base units",
        "limitations": [
            "Not measured Assam demand",
            "Seasonal effects are hypotheses, not fitted local facts",
            "Not calibrated to GRD",
        ],
        "seed": seed,
        "as_of": str(as_of),
        "generator_version": "assam-v1",
    }
    digest = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()
    dataset = Dataset(org_id=org.id, name=manifest["name"], digest=digest, provenance=manifest, row_count=0)
    s.add(dataset)
    s.flush()
    rng = np.random.default_rng(seed)
    count = 0
    for li, loc in enumerate(locations):
        for pi, prod in enumerate(products):
            for i in range(735):
                day = as_of - timedelta(days=734 - i)
                mean = 0 if li == 0 else (0.3 if pi == 3 else 8 + pi * 2 + li)
                # Explicitly assumed monsoon/calendar effects for scenario testing only.
                mean *= 1 + 0.25 * math.sin(2 * math.pi * day.timetuple().tm_yday / 365)
                qty = int(rng.poisson(max(0, mean)))
                s.add(
                    Demand(
                        org_id=org.id,
                        date=day,
                        product_id=prod.id,
                        location_id=loc.id,
                        quantity=qty,
                        measure="requested",
                        dataset_id=dataset.id,
                    )
                )
                count += 1
            qty = 5000 if li == 0 else 800 if li == 1 else 10 if li == 3 else 150
            batch = Batch(
                org_id=org.id,
                product_id=prod.id,
                location_id=loc.id,
                code=f"DEMO-{li}-{pi}",
                expiry=as_of + timedelta(days=20 if li == 1 else 365),
                quantity=0,
                reserved=0,
            )
            s.add(batch)
            s.flush()
            d.change(s, user, batch, qty, "demo_opening", dataset.id)
    dataset.row_count = count
    d.audit(s, user, "demo.seeded", dataset.id, manifest, [x.id for x in locations])
    return {
        "organisation_id": org.id,
        "admin_email": email,
        "as_of": str(as_of),
        "dataset_id": dataset.id,
        "locations": {x.name: x.id for x in locations},
        "products": {x.name: x.id for x in products},
        "evidence_type": "synthetic",
        "demand_rows": count,
    }


def add_pack_scenario(s, email):
    """Install one additional scenario product without rewriting the stress case."""
    user = s.scalar(select(User).where(User.email == email.lower(), User.role == "admin", User.active))
    if not user:
        return None
    org = s.scalar(select(Organisation).where(Organisation.id == user.org_id).with_for_update())
    if org.mode != "synthetic" or org.scenario_on is None:
        return None
    existing = s.scalars(select(Dataset).where(Dataset.org_id == org.id))
    if not any(dataset.provenance.get("generator_version") == "assam-v1" for dataset in existing):
        return None
    prefix = org.id[:8]
    product_id = prefix + "-P-strips"
    if s.get(Product, product_id):
        return product_id
    locations = [s.get(Location, prefix + "-L" + str(i)) for i in range(5)]
    if not all(loc and loc.org_id == org.id for loc in locations):
        raise ValueError("Assam scenario needs the five original seeded locations")

    as_of = org.scenario_on
    manifest = {
        "name": "Assam strip replenishment scenario",
        "evidence_type": "synthetic",
        "geography": "Five fictional Assam operating sites",
        "source_url": "grd.demo.add_pack_scenario",
        "licence": "Project-generated synthetic demand and opening stock",
        "units": "10-tablet strips",
        "limitations": [
            "Illustrative distribution volumes and 20-strip cartons",
            "Seasonality is generated and is not evidence about Assam demand",
        ],
        "seed": 42,
        "as_of": str(as_of),
        "generator_version": "assam-strips-v1",
    }
    product = Product(
        id=product_id,
        org_id=org.id,
        name="Paracetamol 500 mg · 10-tablet strips",
        base_unit="strip",
        pack_size=20,
        unit_cost_paise=900,
        unit_conversions={"carton": 20},
        provenance={
            "evidence_type": "synthetic",
            "review_start_location": locations[3].id,
            "note": "Illustrative packaging and costs; review starts at Silchar",
        },
    )
    weeks = 157
    days = 7 * weeks
    dataset = Dataset(
        org_id=org.id,
        name=manifest["name"],
        digest=hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest(),
        provenance=manifest,
        row_count=days * len(locations),
    )
    s.add_all([product, dataset])
    s.flush()
    rng = np.random.default_rng(manifest["seed"])
    for loc, mean, opening in zip(locations, (0, 210, 175, 180, 140), (48000, 9000, 6500, 2200, 5500)):
        rows = []
        for i in range(days):
            day = as_of - timedelta(days=days - 1 - i)
            rate = mean * (1 + 0.10 * math.sin(2 * math.pi * day.timetuple().tm_yday / 365))
            rows.append({
                "org_id": org.id,
                "date": day,
                "product_id": product_id,
                "location_id": loc.id,
                "quantity": int(rng.poisson(rate)),
                "measure": "requested",
                "dataset_id": dataset.id,
            })
        s.execute(insert(Demand), rows)
        batch = Batch(
            org_id=org.id,
            product_id=product_id,
            location_id=loc.id,
            code=f"STRIP-{loc.id.rsplit('-', 1)[-1]}",
            expiry=as_of + timedelta(days=120),
            quantity=0,
            reserved=0,
        )
        s.add(batch)
        s.flush()
        d.change(s, user, batch, opening, "demo_opening", dataset.id)
    inputs = {"product_id": product_id, "location_id": locations[3].id, "as_of": str(as_of)}
    s.add_all([
        Job(org_id=org.id, actor_id=user.id, kind="forecast", payload={
            **inputs, "measure": "requested", "horizons": [1, 2, 4],
        }),
        Job(org_id=org.id, actor_id=user.id, kind="simulation", payload={
            **inputs, "seed": 42, "days": 90, "lead_days": 5, "proposed_safety_days": 2,
        }),
    ])
    org.revision += 1
    d.audit(s, user, "demo.pack_scenario_added", dataset.id, manifest, [loc.id for loc in locations])
    return product_id
